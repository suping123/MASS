"""货类词典 —— 全项目唯一一份。

为什么单独抽一个模块：货类曾经有三份词表，互不同步。

  * ``sca/intake.py::_CARGO_RULES``        —— 决定落单时 ``cargo_type`` 是什么
  * ``sca/platform/agents/slots.py::_CARGO_WORDS`` —— 决定对话里"用户提没提货类"
  * ``sca/platform/services/advice.py::CARGO_KB``  —— 决定知识问答怎么答

三份各写各的，现象就出来了：用户在对话里说「粗加工蚕丝」——

  * ``slots`` 的词表里没有"蚕丝"→ 判定"没提货类"→ 槽位一直空着；
  * 就算填上了，``intake`` 也没有纺织品的规则 → 落成「普货」；
  * 而用户去问「纺织品要注意什么」，``advice`` 又答得头头是道。

同一票货在三个地方叫三个名字，用户看到的就是"我说了它听不懂"。

依赖方向：内核（intake）与平台（agents/services）都要用，所以放在 ``sca/``
顶层，**不 import 任何平台代码**；平台侧从这里取，不再自带词表。
"""
