# 别名 -> 标准名；**按别名长度倒序**，保证"医药冷链"先于"冷链"、
# "危化品"先于"化工品"命中。顺序错了就会把具体类别吞进宽类别里。
ALIAS_INDEX: List[Tuple[str, str]] = sorted(
    [(a, name) for name, meta in CARGO_KB.items()
     for a in (meta.get("alias") or []) + [name]],
    key=lambda kv: -len(kv[0]),
)

CATEGORIES: List[str] = list(CARGO_KB)

# 归类提示：说的是上位/口语词、被归到标准类时，如实告诉用户按什么算。
# 归并本身就是一种判断，藏着不说等于让用户以为系统认出了"农产品"这个类目。
