def find_cargo(text: str) -> Optional[str]:
    """从一句话里认出货类；认不出返回 None。

    认不出就返回 None 是刻意的：调用方要么反问用户，要么留空。用"普货"
    兜底等于替用户做了一个会影响选车与合规的判断。
    """
    t = text or ""
    for alias, name in ALIAS_INDEX:
        if alias in t:
            return name
    return None


def classify_cargo(text: str) -> Tuple[Optional[str], str]:
    """返回 (标准类名, 命中的原词)。没命中时原词为空串。"""
    t = text or ""
    for alias, name in ALIAS_INDEX:
        if alias in t:
            return name, alias
    return None, ""


def cargo_mentioned(text: str) -> bool:
    """用户是否真的提了货类（用于"不拿默认普货冒充用户意图"）。"""
    return find_cargo(text) is not None


def guess_note(alias: str) -> str:
    return GUESS_NOTE.get((alias or "").strip(), "")


# 货类自带的运输属性：温控 / 危险品。
# 这两个标志决定"能不能用普通车、要不要资质校验"，猜错代价高，
# 所以只由标准货类推导，不从用户句子里另找线索拼。
_TEMP_CATEGORIES = ("冷链", "生鲜冷链", "医药冷链")
_HAZ_CATEGORIES = ("危险品",)


def flags(cargo_type: Optional[str]) -> Dict[str, bool]:
    name = cargo_type or ""
    if name not in CARGO_KB:
        name = find_cargo(name) or name
    return {"temp_ctrl": name in _TEMP_CATEGORIES,
            "hazmat": name in _HAZ_CATEGORIES}


def cargo_meta(cargo_type: Optional[str]) -> Dict[str, Any]:
    """按货类取知识条目；没写或没收录的回落普货（调用方需自行标注）。"""
    if cargo_type and cargo_type in CARGO_KB:
        return CARGO_KB[cargo_type]
    guess = find_cargo(cargo_type or "")
    if guess:
        return CARGO_KB[guess]
    return CARGO_KB["普货"]


def option_lines(numbered: bool = True) -> List[str]:
    """「有什么货类」的答案：一行一类，带一句人话。"""
    out: List[str] = []
    for i, name in enumerate(CATEGORIES, 1):
        hint = CARGO_KB[name].get("hint") or ""
        out.append(f"{i}. {name} —— {hint}" if numbered else f"· {name}：{hint}")
    return out


def options_text(tail: str = "") -> str:
    head = "可选货类（说名称，或直接回编号）："
    body = "\n".join(option_lines())
    out = head + "\n" + body
    if tail:
        out += "\n" + tail
    return out


def by_index(text: str) -> Optional[str]:
    """把纯数字编号翻译成货类（只在"正在问货类"时调用）。"""
    t = (text or "").strip()
    if not re.fullmatch(r"\d{1,2}", t):
        return None
    i = int(t)
    if 1 <= i <= len(CATEGORIES):
        return CATEGORIES[i - 1]
    return None


